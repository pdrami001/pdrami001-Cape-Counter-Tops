-- Additive migration: review and apply separately. No product/project rows or buckets are changed.
create table public.homepage_content (
  id smallint primary key default 1 check (id = 1),
  content jsonb not null check (
    jsonb_typeof(content) = 'object'
    and content ?& array['hero', 'materials']
    and jsonb_typeof(content->'hero') = 'object'
    and jsonb_typeof(content->'materials') = 'object'
    and (content->'materials') ?& array['granite', 'quartz', 'sintered_stone']
    and octet_length(content::text) <= 16000
  ),
  revision integer not null default 0 check (revision >= 0),
  updated_at timestamptz not null default now()
);

-- Revisions are generated by the database, including updates made through the Data API.
create function public.homepage_content_revision()
returns trigger language plpgsql security invoker set search_path = '' as $$
begin
  new.revision = old.revision + 1;
  new.updated_at = now();
  return new;
end;
$$;
revoke all on function public.homepage_content_revision() from public;
create trigger homepage_content_revision before update on public.homepage_content
for each row execute function public.homepage_content_revision();

alter table public.homepage_content enable row level security;
revoke all on public.homepage_content from anon, authenticated;
grant select on public.homepage_content to anon, authenticated;
grant update (content) on public.homepage_content to authenticated;
revoke insert, delete, truncate on public.homepage_content from anon, authenticated;

create policy "Homepage content is publicly readable" on public.homepage_content
for select to anon, authenticated using (true);
create policy "Only listed admins can publish homepage content" on public.homepage_content
for update to authenticated
using (exists (select 1 from public.admin_users where user_id = (select auth.uid())))
with check (exists (select 1 from public.admin_users where user_id = (select auth.uid())));

-- Reuse product-images and its existing admin-only INSERT / public SELECT policies.
-- Restrictive policies intersect with those policies; they grant no new access.
create policy "Homepage image paths are immutable on update" on storage.objects
as restrictive for update to authenticated
using (not (bucket_id = 'product-images' and name like 'homepage/%'))
with check (not (bucket_id = 'product-images' and name like 'homepage/%'));
create policy "Homepage image files are retained on removal" on storage.objects
as restrictive for delete to authenticated
using (not (bucket_id = 'product-images' and name like 'homepage/%'));
create policy "Homepage uploads use unique image paths" on storage.objects
as restrictive for insert to authenticated with check (
  not (bucket_id = 'product-images' and name like 'homepage/%')
  or (name ~ '^homepage/[0-9a-f-]{36}\.(jpg|png|webp)$'
      and exists (select 1 from public.admin_users where user_id = (select auth.uid())))
);

